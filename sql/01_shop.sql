-- 01_shop.sql  (run as superuser, connected to the project database)
-- Owner: M1 (Dustin Dowell); customers/orders originally by Quan Nguyen.
--
-- The proposal's six-table shop schema with a small DETERMINISTIC seed:
--   customers 1,000 · products 200 · inventory 200 · orders 10,000
--   order_items ~20,000 · payments ~7,500
-- Every value is a pure function of the row number (no random()), so test
-- databases are identical on every build. The proposal-scale data set
-- (~100k customers / ~1M orders) is loaded on demand by workload/seed_data.py.
--
-- Deliberately MISSING index (missing-index scenario, proposal 6.2):
--   shop.order_items(product_id) has no index, so "which orders contain
--   product X" is a sequential scan of order_items. The fix demonstrated with
--   EXPLAIN (ANALYZE, BUFFERS) is:
--     CREATE INDEX order_items_product_id_idx ON shop.order_items(product_id);
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA IF NOT EXISTS shop;

-- one statement so dependency order does not matter
DROP TABLE IF EXISTS shop.payments, shop.order_items, shop.inventory,
                     shop.orders, shop.products, shop.customers;

CREATE TABLE shop.customers (
    customer_id  integer PRIMARY KEY,
    email        text    NOT NULL UNIQUE,
    full_name    text    NOT NULL,
    region       text    NOT NULL,
    created_at   timestamptz NOT NULL,
    balance      numeric(12,2) NOT NULL DEFAULT 0
);

CREATE TABLE shop.products (
    product_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text    NOT NULL UNIQUE,
    name         text    NOT NULL,
    category     text    NOT NULL,
    unit_price   numeric(10,2) NOT NULL CHECK (unit_price >= 0),
    created_at   timestamptz NOT NULL
);

CREATE TABLE shop.inventory (
    product_id       integer PRIMARY KEY REFERENCES shop.products(product_id),
    quantity_on_hand integer NOT NULL CHECK (quantity_on_hand >= 0),
    reorder_level    integer NOT NULL CHECK (reorder_level >= 0),
    updated_at       timestamptz NOT NULL
);

CREATE TABLE shop.orders (
    order_id     integer PRIMARY KEY,
    customer_id  integer NOT NULL REFERENCES shop.customers(customer_id),
    ordered_at   timestamptz NOT NULL,
    status       text    NOT NULL CHECK (status IN ('new','paid','shipped','cancelled')),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0)
);
CREATE INDEX orders_customer_id_idx ON shop.orders(customer_id);

CREATE TABLE shop.order_items (
    order_id     integer  NOT NULL REFERENCES shop.orders(order_id) ON DELETE CASCADE,
    line_no      smallint NOT NULL CHECK (line_no > 0),
    product_id   integer  NOT NULL REFERENCES shop.products(product_id),
    quantity     integer  NOT NULL CHECK (quantity > 0),
    unit_price   numeric(10,2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, line_no)
);
-- NOTE: no index on order_items(product_id) -- intentional, see header.

CREATE TABLE shop.payments (
    payment_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     integer NOT NULL REFERENCES shop.orders(order_id),
    paid_at      timestamptz NOT NULL,
    amount       numeric(12,2) NOT NULL CHECK (amount >= 0),
    method       text NOT NULL CHECK (method IN ('card','paypal','gift_card','bank_transfer')),
    status       text NOT NULL CHECK (status IN ('authorized','captured','refunded','failed'))
);
CREATE INDEX payments_order_id_idx ON shop.payments(order_id);

-- ---------------------------------------------------------------------------
-- deterministic seed
-- ---------------------------------------------------------------------------
INSERT INTO shop.customers (customer_id, email, full_name, region, created_at, balance)
SELECT g,
       'customer' || g || '@example.test',
       'Customer ' || g,
       (ARRAY['north','south','east','west'])[1 + g % 4],
       timestamptz '2026-01-01 00:00:00+00' + (g || ' hours')::interval,
       (g % 500)::numeric
FROM generate_series(1, 1000) AS g;

INSERT INTO shop.products (product_id, sku, name, category, unit_price, created_at)
OVERRIDING SYSTEM VALUE
SELECT g,
       'SKU-' || lpad(g::text, 5, '0'),
       'Product ' || g,
       (ARRAY['books','electronics','home','toys','grocery'])[1 + g % 5],
       round(((g * 53) % 9900 + 100) / 100.0, 2),          -- 1.00 .. 99.99
       timestamptz '2025-12-01 00:00:00+00' + (g || ' hours')::interval
FROM generate_series(1, 200) AS g;
ALTER TABLE shop.products ALTER COLUMN product_id RESTART WITH 201;  -- after the explicit ids

INSERT INTO shop.inventory (product_id, quantity_on_hand, reorder_level, updated_at)
SELECT g, (g * 17) % 500, 25 + g % 50, timestamptz '2026-02-01 00:00:00+00'
FROM generate_series(1, 200) AS g;

-- order lines first (in a temp table) so each order's total_amount is the sum
-- of its lines without a second UPDATE pass that would leave dead tuples
-- (plain TEMP table: psql autocommits each statement, so ON COMMIT DROP would
-- discard it immediately)
DROP TABLE IF EXISTS pg_temp.seed_items;
CREATE TEMP TABLE seed_items AS
SELECT o AS order_id,
       l::smallint AS line_no,
       1 + (o * 13 + l * 31) % 200 AS product_id,
       1 + (o + l) % 4 AS quantity
FROM generate_series(1, 10000) AS o
CROSS JOIN LATERAL generate_series(1, 1 + o % 3) AS l;

INSERT INTO shop.orders (order_id, customer_id, ordered_at, status, total_amount)
SELECT g,
       1 + (g * 7) % 1000,
       timestamptz '2026-02-01 00:00:00+00' + (g || ' minutes')::interval,
       (ARRAY['new','paid','shipped','cancelled'])[1 + g % 4],
       t.total
FROM generate_series(1, 10000) AS g
JOIN (SELECT si.order_id, sum(si.quantity * p.unit_price) AS total
        FROM seed_items si JOIN shop.products p USING (product_id)
       GROUP BY si.order_id) t ON t.order_id = g;

INSERT INTO shop.order_items (order_id, line_no, product_id, quantity, unit_price)
SELECT si.order_id, si.line_no, si.product_id, si.quantity, p.unit_price
FROM seed_items si JOIN shop.products p USING (product_id)
ORDER BY si.order_id, si.line_no;

DROP TABLE seed_items;

-- one payment per order that left the 'new' state
INSERT INTO shop.payments (order_id, paid_at, amount, method, status)
SELECT o.order_id,
       o.ordered_at + interval '5 minutes',
       o.total_amount,
       (ARRAY['card','paypal','gift_card','bank_transfer'])[1 + o.order_id % 4],
       CASE o.status WHEN 'cancelled' THEN 'refunded' ELSE 'captured' END
FROM shop.orders o
WHERE o.status <> 'new'
ORDER BY o.order_id;

ANALYZE shop.customers;
ANALYZE shop.products;
ANALYZE shop.inventory;
ANALYZE shop.orders;
ANALYZE shop.order_items;
ANALYZE shop.payments;

-- least privilege: the application role can use shop tables only (no DELETE, no DDL)
GRANT USAGE ON SCHEMA shop TO shop_app;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA shop TO shop_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA shop TO shop_app;
